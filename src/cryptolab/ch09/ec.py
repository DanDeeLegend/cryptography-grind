"""Assignments 9.1 / 9.6 support: short-Weierstrass elliptic-curve arithmetic over a prime field.

Curve: y^2 = x^3 + a*x + b (mod p). Points are (x, y) tuples; the point at infinity (the group identity) is None.
Written for clarity and verified against OpenSSL (via `cryptography`) on NIST P-256. Not constant-time.
"""
from __future__ import annotations

from dataclasses import dataclass

from . import toy_params as T

Point = tuple[int, int] | None


@dataclass(frozen=True)
class Curve:
    name: str
    p: int
    a: int
    b: int
    g: tuple[int, int]
    n: int          # order of the subgroup generated by g


_P256_P = 2 ** 256 - 2 ** 224 + 2 ** 192 + 2 ** 96 - 1
P256 = Curve("NIST P-256", _P256_P, _P256_P - 3,
             0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B,
             (0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
              0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5),
             0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551)
TEXTBOOK = Curve("textbook y^2=x^3+2x+2 over F17", 17, 2, 2, (5, 1), 19)
TOY = Curve("toy 20-bit curve", T.P, T.A, T.B, (T.GX, T.GY), T.N)


def inv(x: int, p: int) -> int:
    return pow(x, -1, p)


def on_curve(c: Curve, pt: Point) -> bool:
    return pt is None or (pt[1] ** 2 - pt[0] ** 3 - c.a * pt[0] - c.b) % c.p == 0


def neg(c: Curve, pt: Point) -> Point:
    return None if pt is None else (pt[0], -pt[1] % c.p)


def add(c: Curve, p1: Point, p2: Point) -> Point:
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    (x1, y1), (x2, y2) = p1, p2
    if x1 == x2:
        if (y1 + y2) % c.p == 0:
            return None                                   # P + (-P) = infinity (also covers doubling a point with y = 0)
        lam = (3 * x1 * x1 + c.a) * inv(2 * y1, c.p) % c.p      # tangent slope: doubling
    else:
        lam = (y2 - y1) * inv(x2 - x1, c.p) % c.p                # chord slope: addition
    x3 = (lam * lam - x1 - x2) % c.p
    return x3, (lam * (x1 - x3) - y1) % c.p


def scalar_mult(c: Curve, k: int, pt: Point) -> Point:
    """k * pt by double-and-add (the elliptic-curve twin of square-and-multiply)."""
    if k < 0:
        return scalar_mult(c, -k, neg(c, pt))
    result: Point = None
    for bit in bin(k)[2:] if k else "":
        result = add(c, result, result)
        if bit == "1":
            result = add(c, result, pt)
    return result


def describe_add(c: Curve, p1: Point, p2: Point) -> tuple[Point, list[str]]:
    """Return (P1 + P2, the intermediate values of the computation, one per line)."""
    (x1, y1), (x2, y2) = p1, p2
    p = c.p
    lines = [f"P1 = {p1}, P2 = {p2}   (mod {p})"]
    if x1 == x2 and y1 == y2:
        num, den = (3 * x1 * x1 + c.a) % p, 2 * y1 % p
        lines.append(f"doubling: slope = (3*x1^2 + a) / (2*y1) = {num} / {den}")
    else:
        num, den = (y2 - y1) % p, (x2 - x1) % p
        lines.append(f"addition: slope = (y2 - y1) / (x2 - x1) = {num} / {den}")
    lam = num * inv(den, p) % p
    lines.append(f"          {den}^-1 = {inv(den, p)},  slope = {lam}")
    x3 = (lam * lam - x1 - x2) % p
    y3 = (lam * (x1 - x3) - y1) % p
    lines.append(f"x3 = slope^2 - x1 - x2 = {x3}")
    lines.append(f"y3 = slope*(x1 - x3) - y1 = {y3}")
    return (x3, y3), lines


def worked_example() -> str:
    c, g = TEXTBOOK, TEXTBOOK.g
    out = [f"Curve {c.name}, P = G = {g}, group order {c.n}", ""]
    r, lines = describe_add(c, g, g)
    out += ["2P (point doubling):"] + ["  " + l for l in lines] + [""]
    r3, lines = describe_add(c, r, g)
    out += ["3P = 2P + P (point addition):"] + ["  " + l for l in lines] + ["", "all multiples of P:"]
    out.append("  " + "  ".join(f"{k}P={scalar_mult(c, k, g)}" for k in range(1, c.n + 1)))
    return "\n".join(out)


if __name__ == "__main__":
    print(worked_example())
